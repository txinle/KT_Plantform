async function capture(page: Page, info: TestInfo, name: string) {
  for (const [label, width, height] of [['desktop', 1440, 900], ['mobile', 390, 844], ['small-viewport', 720, 450]] as const) {
    await page.setViewportSize({ width, height })
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width + 1)
    const dialog = page.locator('dialog[open]')
    if (await dialog.count()) {
      const bounds = (await dialog.last().boundingBox())!
      expect(bounds.x).toBeGreaterThanOrEqual(0)
      expect(bounds.y).toBeGreaterThanOrEqual(0)
      expect(bounds.x + bounds.width).toBeLessThanOrEqual(width + 1)
      expect(bounds.y + bounds.height).toBeLessThanOrEqual(height + 1)
    }
    await page.screenshot({ path: info.outputPath(`${name}-${label}.png`), fullPage: true })
  }
  await page.setViewportSize({ width: 1440, height: 900 })
}

