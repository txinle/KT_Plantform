#!/usr/bin/env sh
set -eu
[ "${SCHOOL_RUNTIME_ISOLATION_ENABLED:-0}" = "1" ] || exit 1
: "${POSTGRES_DB:?}" "${POSTGRES_USER:?}" "${POSTGRES_PASSWORD:?}"
PGBOUNCER_SERVER_HOST=${PGBOUNCER_SERVER_HOST:-db}
ASSESSMENT_STARTUP_DB_CONNECTIONS=${ASSESSMENT_STARTUP_DB_CONNECTIONS:-2}
ASSESSMENT_REMAINING_DB_CONNECTIONS=${ASSESSMENT_REMAINING_DB_CONNECTIONS:-6}
ASSESSMENT_AUTH_WORKERS=${ASSESSMENT_AUTH_WORKERS:-4}
ASSESSMENT_CAPTURE_WORKERS=${ASSESSMENT_CAPTURE_WORKERS:-4}
ASSESSMENT_STUDENT_READ_WORKERS=${ASSESSMENT_STUDENT_READ_WORKERS:-2}
case "$ASSESSMENT_STARTUP_DB_CONNECTIONS:$ASSESSMENT_REMAINING_DB_CONNECTIONS:$ASSESSMENT_AUTH_WORKERS:$ASSESSMENT_CAPTURE_WORKERS:$ASSESSMENT_STUDENT_READ_WORKERS" in *[!0-9:]*) echo "Invalid school database allocation" >&2; exit 1;; esac
for value in "$ASSESSMENT_STARTUP_DB_CONNECTIONS" "$ASSESSMENT_REMAINING_DB_CONNECTIONS" "$ASSESSMENT_AUTH_WORKERS" "$ASSESSMENT_CAPTURE_WORKERS" "$ASSESSMENT_STUDENT_READ_WORKERS"; do
    [ "$value" -ge 1 ] || exit 1
    if [ "${SCHOOL_POOL_PROFILE:-}" != "shared-entry-v3" ]; then [ "$value" -le 20 ] || exit 1; fi
done
ASSESSMENT_ENTRY_DB_CONNECTIONS=${ASSESSMENT_ENTRY_DB_CONNECTIONS:-0}
ASSESSMENT_CAPTURE_DB_CONNECTIONS=${ASSESSMENT_CAPTURE_DB_CONNECTIONS:-$ASSESSMENT_CAPTURE_WORKERS}
ASSESSMENT_BACKGROUND_DB_CONNECTIONS=${ASSESSMENT_BACKGROUND_DB_CONNECTIONS:-2}
ASSESSMENT_SUBMISSION_DB_CONNECTIONS=${ASSESSMENT_SUBMISSION_DB_CONNECTIONS:-1}
ASSESSMENT_CORE_WORKERS=${ASSESSMENT_CORE_WORKERS:-1}
ASSESSMENT_CORE_DB_CONNECTIONS=${ASSESSMENT_CORE_DB_CONNECTIONS:-1}
ASSESSMENT_TEACHER_WORKERS=${ASSESSMENT_TEACHER_WORKERS:-1}
ASSESSMENT_TEACHER_DB_CONNECTIONS=${ASSESSMENT_TEACHER_DB_CONNECTIONS:-1}
PGBOUNCER_MAX_CLIENT_CONN=${PGBOUNCER_MAX_CLIENT_CONN:-200}
ASSESSMENT_ENTRY_DB_RESERVE_CONNECTIONS=${ASSESSMENT_ENTRY_DB_RESERVE_CONNECTIONS:-0}
ASSESSMENT_REMAINING_DB_RESERVE_CONNECTIONS=${ASSESSMENT_REMAINING_DB_RESERVE_CONNECTIONS:-2}
ASSESSMENT_CAPTURE_DB_RESERVE_CONNECTIONS=${ASSESSMENT_CAPTURE_DB_RESERVE_CONNECTIONS:-1}
ASSESSMENT_CORE_DB_RESERVE_CONNECTIONS=${ASSESSMENT_CORE_DB_RESERVE_CONNECTIONS:-0}
ASSESSMENT_TEACHER_DB_RESERVE_CONNECTIONS=${ASSESSMENT_TEACHER_DB_RESERVE_CONNECTIONS:-0}
ASSESSMENT_BACKGROUND_DB_RESERVE_CONNECTIONS=${ASSESSMENT_BACKGROUND_DB_RESERVE_CONNECTIONS:-0}
ASSESSMENT_SUBMISSION_DB_RESERVE_CONNECTIONS=${ASSESSMENT_SUBMISSION_DB_RESERVE_CONNECTIONS:-0}
if [ "${SCHOOL_POOL_PROFILE:-}" = "shared-entry-v3" ]; then
    ASSESSMENT_SUBMISSION_WORKERS=${ASSESSMENT_SUBMISSION_WORKERS:-1}
    ASSESSMENT_SUBMISSION_DB_CONNECTIONS=${ASSESSMENT_SUBMISSION_DB_CONNECTIONS:-1}
    ASSESSMENT_ANALYTICS_WORKERS=${ASSESSMENT_ANALYTICS_WORKERS:-1}
    ASSESSMENT_BACKGROUND_DB_CONNECTIONS=${ASSESSMENT_BACKGROUND_DB_CONNECTIONS:-2}
    ASSESSMENT_ENTRY_STARTUP_BURST=${ASSESSMENT_ENTRY_STARTUP_BURST:-8}
    ASSESSMENT_ENTRY_STARTUP_RATE=${ASSESSMENT_ENTRY_STARTUP_RATE:-64}
    SCHOOL_DB_MAX_CONNECTIONS=${SCHOOL_DB_MAX_CONNECTIONS:-64}
    SCHOOL_DB_RESERVED_CONNECTIONS=${SCHOOL_DB_RESERVED_CONNECTIONS:-3}
    SCHOOL_DB_DIRECT_CONNECTIONS=${SCHOOL_DB_DIRECT_CONNECTIONS:-1}
    SCHOOL_DB_MONITOR_CONNECTIONS=${SCHOOL_DB_MONITOR_CONNECTIONS:-2}
    SCHOOL_DB_MAINTENANCE_CONNECTIONS=${SCHOOL_DB_MAINTENANCE_CONNECTIONS:-2}
    SCHOOL_DB_ROLLING_OVERLAP_CONNECTIONS=${SCHOOL_DB_ROLLING_OVERLAP_CONNECTIONS:-0}
    for value in "${ASSESSMENT_ENTRY_WORKERS:-}" "${ASSESSMENT_ENTRY_DB_CONNECTIONS:-}" "${ASSESSMENT_REMAINING_WORKERS:-}" "${ASSESSMENT_REMAINING_DB_CONNECTIONS:-}" "${ASSESSMENT_CAPTURE_WORKERS:-}" "${ASSESSMENT_CAPTURE_DB_CONNECTIONS:-}" "${ASSESSMENT_ENTRY_LOGIN_LIMIT:-}" "${ASSESSMENT_ENTRY_STARTUP_LIMIT:-}" "${ASSESSMENT_ENTRY_HEAVY_LIMIT:-}" "${ASSESSMENT_ADMISSION_CAPACITY:-}" "${ASSESSMENT_CORE_WORKERS:-}" "${ASSESSMENT_CORE_DB_CONNECTIONS:-}" "${ASSESSMENT_TEACHER_WORKERS:-}" "${ASSESSMENT_TEACHER_DB_CONNECTIONS:-}" "${ASSESSMENT_SUBMISSION_WORKERS:-}" "${ASSESSMENT_SUBMISSION_DB_CONNECTIONS:-}" "${ASSESSMENT_ANALYTICS_WORKERS:-}" "${ASSESSMENT_BACKGROUND_DB_CONNECTIONS:-}" "${ASSESSMENT_ENTRY_STARTUP_BURST:-}" "${ASSESSMENT_ENTRY_STARTUP_RATE:-}" "${PGBOUNCER_MAX_CLIENT_CONN:-}" "${SCHOOL_DB_MAX_CONNECTIONS:-}"; do
        case "$value" in ''|*[!0-9]*) echo "Invalid capacity v3 budget" >&2; exit 1;; esac
        [ "$value" -ge 1 ] || exit 1
    done
    for value in "${SCHOOL_DB_RESERVED_CONNECTIONS:-}" "${SCHOOL_DB_DIRECT_CONNECTIONS:-}" "${SCHOOL_DB_MONITOR_CONNECTIONS:-}" "${SCHOOL_DB_MAINTENANCE_CONNECTIONS:-}" "${SCHOOL_DB_ROLLING_OVERLAP_CONNECTIONS:-}" "${ASSESSMENT_ENTRY_DB_RESERVE_CONNECTIONS:-}" "${ASSESSMENT_REMAINING_DB_RESERVE_CONNECTIONS:-}" "${ASSESSMENT_CAPTURE_DB_RESERVE_CONNECTIONS:-}" "${ASSESSMENT_CORE_DB_RESERVE_CONNECTIONS:-}" "${ASSESSMENT_TEACHER_DB_RESERVE_CONNECTIONS:-}" "${ASSESSMENT_BACKGROUND_DB_RESERVE_CONNECTIONS:-}" "${ASSESSMENT_SUBMISSION_DB_RESERVE_CONNECTIONS:-}"; do
        case "$value" in ''|*[!0-9]*) echo "Invalid capacity v3 budget" >&2; exit 1;; esac
        [ "$value" -ge 0 ] || exit 1
    done
    [ "${ASSESSMENT_PREPARED_ADMISSION_MODE:-}" = "postgres_transaction" ] && \
    [ "${ASSESSMENT_ADMISSION_ENABLED:-0}" = "1" ] && [ "${ASSESSMENT_ADMISSION_GLOBAL_ENABLED:-0}" = "1" ] && \
    [ "$ASSESSMENT_ENTRY_LOGIN_LIMIT" -le "$ASSESSMENT_ENTRY_HEAVY_LIMIT" ] && \
    [ "$ASSESSMENT_ENTRY_STARTUP_LIMIT" -le "$ASSESSMENT_ENTRY_HEAVY_LIMIT" ] && \
    [ "$ASSESSMENT_ENTRY_HEAVY_LIMIT" -lt "$ASSESSMENT_ENTRY_WORKERS" ] && \
    [ "$ASSESSMENT_ADMISSION_CAPACITY" -le "$ASSESSMENT_ENTRY_WORKERS" ] && \
    [ "$ASSESSMENT_ADMISSION_CAPACITY" -le "$ASSESSMENT_ENTRY_STARTUP_LIMIT" ] && \
    [ "$ASSESSMENT_ADMISSION_CAPACITY" -le "$ASSESSMENT_ENTRY_DB_CONNECTIONS" ] && \
    [ "$ASSESSMENT_BACKGROUND_DB_CONNECTIONS" -ge "$((2 * ASSESSMENT_ANALYTICS_WORKERS))" ] && \
    [ "$ASSESSMENT_SUBMISSION_DB_CONNECTIONS" -ge "$ASSESSMENT_SUBMISSION_WORKERS" ] && \
    [ "$((ASSESSMENT_ENTRY_DB_CONNECTIONS + ASSESSMENT_REMAINING_DB_CONNECTIONS + ASSESSMENT_CAPTURE_DB_CONNECTIONS + ASSESSMENT_CORE_DB_CONNECTIONS + ASSESSMENT_TEACHER_DB_CONNECTIONS + ASSESSMENT_BACKGROUND_DB_CONNECTIONS + ASSESSMENT_SUBMISSION_DB_CONNECTIONS + ASSESSMENT_ENTRY_DB_RESERVE_CONNECTIONS + ASSESSMENT_REMAINING_DB_RESERVE_CONNECTIONS + ASSESSMENT_CAPTURE_DB_RESERVE_CONNECTIONS + ASSESSMENT_CORE_DB_RESERVE_CONNECTIONS + ASSESSMENT_TEACHER_DB_RESERVE_CONNECTIONS + ASSESSMENT_BACKGROUND_DB_RESERVE_CONNECTIONS + ASSESSMENT_SUBMISSION_DB_RESERVE_CONNECTIONS + SCHOOL_DB_DIRECT_CONNECTIONS + SCHOOL_DB_MONITOR_CONNECTIONS + SCHOOL_DB_MAINTENANCE_CONNECTIONS + SCHOOL_DB_ROLLING_OVERLAP_CONNECTIONS))" -le "$((SCHOOL_DB_MAX_CONNECTIONS - SCHOOL_DB_RESERVED_CONNECTIONS))" ] || {
        echo "Capacity v3 exceeds worker, ingress or PostgreSQL connection budgets" >&2; exit 1;
    }
elif [ "${SCHOOL_POOL_PROFILE:-}" = "shared-entry-v2" ]; then
    : "${ASSESSMENT_ENTRY_WORKERS:?}" "${ASSESSMENT_ENTRY_LOGIN_LIMIT:?}" "${ASSESSMENT_ENTRY_STARTUP_LIMIT:?}" "${ASSESSMENT_ENTRY_HEAVY_LIMIT:?}"
    : "${ASSESSMENT_REMAINING_WORKERS:?}" "${ASSESSMENT_ADMISSION_CAPACITY:?}" "${ASSESSMENT_SUBMISSION_WORKERS:?}" "${ASSESSMENT_ANALYTICS_WORKERS:?}"
    : "${ASSESSMENT_ENTRY_STARTUP_BURST:?}" "${ASSESSMENT_ENTRY_STARTUP_RATE:?}" "${SCHOOL_DB_MAX_CONNECTIONS:?}" "${SCHOOL_DB_RESERVED_CONNECTIONS:?}"
    : "${SCHOOL_DB_DIRECT_CONNECTIONS:?}" "${SCHOOL_DB_MONITOR_CONNECTIONS:?}" "${SCHOOL_DB_MAINTENANCE_CONNECTIONS:?}" "${SCHOOL_DB_ROLLING_OVERLAP_CONNECTIONS:?}"
    for value in "$ASSESSMENT_ENTRY_WORKERS" "$ASSESSMENT_ENTRY_DB_CONNECTIONS" "$ASSESSMENT_CAPTURE_DB_CONNECTIONS" \
        "$ASSESSMENT_REMAINING_WORKERS" "$ASSESSMENT_ENTRY_LOGIN_LIMIT" "$ASSESSMENT_ENTRY_STARTUP_LIMIT" \
        "$ASSESSMENT_ENTRY_HEAVY_LIMIT" "$ASSESSMENT_ADMISSION_CAPACITY" "$ASSESSMENT_SUBMISSION_WORKERS" \
        "$ASSESSMENT_SUBMISSION_DB_CONNECTIONS" "$ASSESSMENT_ANALYTICS_WORKERS" "$ASSESSMENT_BACKGROUND_DB_CONNECTIONS" \
        "$ASSESSMENT_ENTRY_STARTUP_BURST" "$ASSESSMENT_ENTRY_STARTUP_RATE" "$SCHOOL_DB_MAX_CONNECTIONS" \
        "$SCHOOL_DB_RESERVED_CONNECTIONS" "$SCHOOL_DB_DIRECT_CONNECTIONS" "$SCHOOL_DB_MONITOR_CONNECTIONS" \
        "$SCHOOL_DB_MAINTENANCE_CONNECTIONS" "$SCHOOL_DB_ROLLING_OVERLAP_CONNECTIONS"; do
        case "$value" in ''|*[!0-9]*) echo "Invalid capacity experiment budget" >&2; exit 1;; esac
        [ "$value" -le 128 ] || exit 1
    done
    [ "${ASSESSMENT_PREPARED_ADMISSION_MODE:-}" = "postgres_transaction" ] && \
    [ "${ASSESSMENT_ADMISSION_ENABLED:-0}" = "1" ] && [ "${ASSESSMENT_ADMISSION_GLOBAL_ENABLED:-0}" = "1" ] && \
    { [ "$ASSESSMENT_ENTRY_WORKERS" -eq 15 ] || [ "$ASSESSMENT_ENTRY_WORKERS" -eq 19 ]; } && \
    [ "$ASSESSMENT_ENTRY_DB_CONNECTIONS" -ge 1 ] && [ "$ASSESSMENT_ENTRY_DB_CONNECTIONS" -le 15 ] && \
    [ "$ASSESSMENT_REMAINING_WORKERS" -ge 4 ] && [ "$ASSESSMENT_REMAINING_WORKERS" -le 12 ] && \
    [ "$ASSESSMENT_REMAINING_DB_CONNECTIONS" -ge 4 ] && [ "$ASSESSMENT_REMAINING_DB_CONNECTIONS" -le 12 ] && \
    [ "$ASSESSMENT_CAPTURE_WORKERS" -eq 3 ] && [ "$ASSESSMENT_CAPTURE_DB_CONNECTIONS" -eq 3 ] && \
    { [ "$ASSESSMENT_SUBMISSION_WORKERS" -eq 1 ] || [ "$ASSESSMENT_SUBMISSION_WORKERS" -eq 2 ] || [ "$ASSESSMENT_SUBMISSION_WORKERS" -eq 4 ]; } && \
    [ "$ASSESSMENT_SUBMISSION_DB_CONNECTIONS" -eq "$ASSESSMENT_SUBMISSION_WORKERS" ] && \
    { [ "$ASSESSMENT_ANALYTICS_WORKERS" -eq 1 ] || [ "$ASSESSMENT_ANALYTICS_WORKERS" -eq 2 ]; } && \
    [ "$ASSESSMENT_BACKGROUND_DB_CONNECTIONS" -ge "$((2 * ASSESSMENT_ANALYTICS_WORKERS))" ] && [ "$ASSESSMENT_BACKGROUND_DB_CONNECTIONS" -le 4 ] && \
    [ "$ASSESSMENT_ENTRY_HEAVY_LIMIT" -ge 1 ] && [ "$ASSESSMENT_ENTRY_HEAVY_LIMIT" -lt "$ASSESSMENT_ENTRY_WORKERS" ] && \
    [ "$ASSESSMENT_ENTRY_LOGIN_LIMIT" -ge 1 ] && [ "$ASSESSMENT_ENTRY_LOGIN_LIMIT" -le "$ASSESSMENT_ENTRY_HEAVY_LIMIT" ] && \
    [ "$ASSESSMENT_ENTRY_STARTUP_LIMIT" -ge 1 ] && [ "$ASSESSMENT_ENTRY_STARTUP_LIMIT" -le "$ASSESSMENT_ENTRY_HEAVY_LIMIT" ] && \
    [ "$ASSESSMENT_ADMISSION_CAPACITY" -ge 1 ] && [ "$ASSESSMENT_ADMISSION_CAPACITY" -le "$ASSESSMENT_ENTRY_WORKERS" ] && \
    [ "$ASSESSMENT_ADMISSION_CAPACITY" -le "$ASSESSMENT_ENTRY_DB_CONNECTIONS" ] && [ "$ASSESSMENT_ADMISSION_CAPACITY" -le "$ASSESSMENT_ENTRY_STARTUP_LIMIT" ] && \
    { [ "$ASSESSMENT_ENTRY_STARTUP_BURST" -eq 8 ] || [ "$ASSESSMENT_ENTRY_STARTUP_BURST" -eq 32 ]; } && \
    [ "$ASSESSMENT_ENTRY_STARTUP_RATE" -eq 64 ] && [ "$SCHOOL_DB_MAX_CONNECTIONS" -eq 64 ] && [ "$SCHOOL_DB_RESERVED_CONNECTIONS" -eq 3 ] && \
    [ "$SCHOOL_DB_DIRECT_CONNECTIONS" -ge 1 ] && [ "$SCHOOL_DB_MONITOR_CONNECTIONS" -ge 2 ] && [ "$SCHOOL_DB_MAINTENANCE_CONNECTIONS" -ge 2 ] && \
    [ "$((ASSESSMENT_ENTRY_DB_CONNECTIONS + ASSESSMENT_REMAINING_DB_CONNECTIONS + ASSESSMENT_CAPTURE_DB_CONNECTIONS + 2 + ASSESSMENT_BACKGROUND_DB_CONNECTIONS + ASSESSMENT_SUBMISSION_DB_CONNECTIONS + 3 + SCHOOL_DB_DIRECT_CONNECTIONS + SCHOOL_DB_MONITOR_CONNECTIONS + SCHOOL_DB_MAINTENANCE_CONNECTIONS + SCHOOL_DB_ROLLING_OVERLAP_CONNECTIONS))" -le "$((SCHOOL_DB_MAX_CONNECTIONS - SCHOOL_DB_RESERVED_CONNECTIONS))" ] || {
        echo "Capacity experiment exceeds approved worker, ingress or PostgreSQL connection budgets" >&2; exit 1;
    }
elif [ "${SCHOOL_POOL_PROFILE:-}" = "shared-entry-v1" ]; then
    : "${ASSESSMENT_ENTRY_WORKERS:?}" "${ASSESSMENT_ENTRY_LOGIN_LIMIT:?}" "${ASSESSMENT_ENTRY_STARTUP_LIMIT:?}" "${ASSESSMENT_ENTRY_HEAVY_LIMIT:?}"
    : "${ASSESSMENT_REMAINING_WORKERS:?}" "${ASSESSMENT_ADMISSION_CAPACITY:?}"
    for value in "$ASSESSMENT_ENTRY_WORKERS" "$ASSESSMENT_ENTRY_DB_CONNECTIONS" "$ASSESSMENT_CAPTURE_DB_CONNECTIONS" \
        "$ASSESSMENT_REMAINING_WORKERS" "$ASSESSMENT_ENTRY_LOGIN_LIMIT" "$ASSESSMENT_ENTRY_STARTUP_LIMIT" \
        "$ASSESSMENT_ENTRY_HEAVY_LIMIT" "$ASSESSMENT_ADMISSION_CAPACITY"; do
        case "$value" in ''|*[!0-9]*) echo "Invalid shared entry budget" >&2; exit 1;; esac
        [ "$value" -ge 1 ] && [ "$value" -le 24 ] || exit 1
    done
    [ "${ASSESSMENT_PREPARED_ADMISSION_MODE:-}" = "postgres_transaction" ] && \
    [ "$((ASSESSMENT_ENTRY_WORKERS + ASSESSMENT_REMAINING_WORKERS + ASSESSMENT_CAPTURE_WORKERS + 2))" -le 24 ] && \
    [ "$((ASSESSMENT_ENTRY_DB_CONNECTIONS + ASSESSMENT_REMAINING_DB_CONNECTIONS + ASSESSMENT_CAPTURE_DB_CONNECTIONS + 5))" -le 23 ] && \
    [ "$ASSESSMENT_REMAINING_WORKERS" -ge 4 ] && [ "$ASSESSMENT_REMAINING_DB_CONNECTIONS" -ge 4 ] && \
    [ "$ASSESSMENT_CAPTURE_WORKERS" -ge 3 ] && [ "$ASSESSMENT_CAPTURE_DB_CONNECTIONS" -ge 3 ] && \
    [ "$ASSESSMENT_ENTRY_HEAVY_LIMIT" -lt "$ASSESSMENT_ENTRY_WORKERS" ] && \
    [ "$ASSESSMENT_ENTRY_LOGIN_LIMIT" -le "$ASSESSMENT_ENTRY_HEAVY_LIMIT" ] && \
    [ "$ASSESSMENT_ENTRY_STARTUP_LIMIT" -le "$ASSESSMENT_ENTRY_HEAVY_LIMIT" ] && \
    [ "$ASSESSMENT_ADMISSION_CAPACITY" -le "$ASSESSMENT_ENTRY_WORKERS" ] && \
    [ "$ASSESSMENT_ADMISSION_CAPACITY" -le "$ASSESSMENT_ENTRY_DB_CONNECTIONS" ] && \
    [ "$ASSESSMENT_ADMISSION_CAPACITY" -le "$ASSESSMENT_ENTRY_STARTUP_LIMIT" ] || {
        echo "Shared entry exceeds independent budgets or removes protected capacity" >&2; exit 1;
    }
elif [ "${ASSESSMENT_PREPARED_ADMISSION_MODE:-redis}" = "postgres_transaction" ]; then
    [ "$((2 + ASSESSMENT_STARTUP_DB_CONNECTIONS + ASSESSMENT_REMAINING_DB_CONNECTIONS + ASSESSMENT_AUTH_WORKERS + ASSESSMENT_CAPTURE_WORKERS + ASSESSMENT_STUDENT_READ_WORKERS))" -eq 20 ] || {
        echo "Student candidate must retain twenty HTTP database connections" >&2; exit 1;
    }
elif [ "$ASSESSMENT_STARTUP_DB_CONNECTIONS" -gt 7 ] || \
   [ "$((ASSESSMENT_STARTUP_DB_CONNECTIONS + ASSESSMENT_REMAINING_DB_CONNECTIONS))" -ne 8 ]; then
    echo "Assessment database pools must split eight connections and preserve write capacity" >&2
    exit 1
fi
if [ "${SCHOOL_POOL_PROFILE:-}" != "shared-entry-v3" ]; then
    ASSESSMENT_CORE_WORKERS=1
    ASSESSMENT_CORE_DB_CONNECTIONS=1
    ASSESSMENT_TEACHER_WORKERS=1
    ASSESSMENT_TEACHER_DB_CONNECTIONS=1
    PGBOUNCER_MAX_CLIENT_CONN=200
    ASSESSMENT_ENTRY_DB_RESERVE_CONNECTIONS=0
    ASSESSMENT_REMAINING_DB_RESERVE_CONNECTIONS=2
    ASSESSMENT_CAPTURE_DB_RESERVE_CONNECTIONS=1
    ASSESSMENT_CORE_DB_RESERVE_CONNECTIONS=0
    ASSESSMENT_TEACHER_DB_RESERVE_CONNECTIONS=0
    ASSESSMENT_BACKGROUND_DB_RESERVE_CONNECTIONS=0
    ASSESSMENT_SUBMISSION_DB_RESERVE_CONNECTIONS=0
fi
# Connection identifiers are supplied by operators; reject template metacharacters.
case "$POSTGRES_DB:$POSTGRES_USER" in *[!a-zA-Z0-9_:]*) echo "Invalid database identifier" >&2; exit 1;; esac
case "$PGBOUNCER_SERVER_HOST" in *[!a-zA-Z0-9_.-]*) echo "Invalid database host" >&2; exit 1;; esac
umask 077
sed -e "s/\${POSTGRES_DB}/$POSTGRES_DB/g" -e "s/\${POSTGRES_USER}/$POSTGRES_USER/g" -e "s/\${PGBOUNCER_SERVER_HOST}/$PGBOUNCER_SERVER_HOST/g" \
    -e "s/\${ASSESSMENT_STARTUP_DB_CONNECTIONS}/$ASSESSMENT_STARTUP_DB_CONNECTIONS/g" \
    -e "s/\${ASSESSMENT_REMAINING_DB_CONNECTIONS}/$ASSESSMENT_REMAINING_DB_CONNECTIONS/g" \
    -e "s/\${ASSESSMENT_AUTH_WORKERS}/$ASSESSMENT_AUTH_WORKERS/g" \
    -e "s/\${ASSESSMENT_CAPTURE_WORKERS}/$ASSESSMENT_CAPTURE_WORKERS/g" \
    -e "s/\${ASSESSMENT_STUDENT_READ_WORKERS}/$ASSESSMENT_STUDENT_READ_WORKERS/g" \
    -e "s/\${ASSESSMENT_ENTRY_DB_CONNECTIONS}/$ASSESSMENT_ENTRY_DB_CONNECTIONS/g" \
    -e "s/\${ASSESSMENT_CAPTURE_DB_CONNECTIONS}/$ASSESSMENT_CAPTURE_DB_CONNECTIONS/g" \
    -e "s/\${ASSESSMENT_BACKGROUND_DB_CONNECTIONS}/$ASSESSMENT_BACKGROUND_DB_CONNECTIONS/g" \
    -e "s/\${ASSESSMENT_SUBMISSION_DB_CONNECTIONS}/$ASSESSMENT_SUBMISSION_DB_CONNECTIONS/g" \
    -e "s/\${ASSESSMENT_CORE_WORKERS}/$ASSESSMENT_CORE_WORKERS/g" \
    -e "s/\${ASSESSMENT_CORE_DB_CONNECTIONS}/$ASSESSMENT_CORE_DB_CONNECTIONS/g" \
    -e "s/\${ASSESSMENT_TEACHER_WORKERS}/$ASSESSMENT_TEACHER_WORKERS/g" \
    -e "s/\${ASSESSMENT_TEACHER_DB_CONNECTIONS}/$ASSESSMENT_TEACHER_DB_CONNECTIONS/g" \
    -e "s/\${PGBOUNCER_MAX_CLIENT_CONN}/$PGBOUNCER_MAX_CLIENT_CONN/g" \
    -e "s/\${ASSESSMENT_ENTRY_DB_RESERVE_CONNECTIONS}/$ASSESSMENT_ENTRY_DB_RESERVE_CONNECTIONS/g" \
    -e "s/\${ASSESSMENT_REMAINING_DB_RESERVE_CONNECTIONS}/$ASSESSMENT_REMAINING_DB_RESERVE_CONNECTIONS/g" \
    -e "s/\${ASSESSMENT_CAPTURE_DB_RESERVE_CONNECTIONS}/$ASSESSMENT_CAPTURE_DB_RESERVE_CONNECTIONS/g" \
    -e "s/\${ASSESSMENT_CORE_DB_RESERVE_CONNECTIONS}/$ASSESSMENT_CORE_DB_RESERVE_CONNECTIONS/g" \
    -e "s/\${ASSESSMENT_TEACHER_DB_RESERVE_CONNECTIONS}/$ASSESSMENT_TEACHER_DB_RESERVE_CONNECTIONS/g" \
    -e "s/\${ASSESSMENT_BACKGROUND_DB_RESERVE_CONNECTIONS}/$ASSESSMENT_BACKGROUND_DB_RESERVE_CONNECTIONS/g" \
    -e "s/\${ASSESSMENT_SUBMISSION_DB_RESERVE_CONNECTIONS}/$ASSESSMENT_SUBMISSION_DB_RESERVE_CONNECTIONS/g" \
    /school/pgbouncer.ini.template > /tmp/pgbouncer-school.ini
if grep -q '\${' /tmp/pgbouncer-school.ini; then
    echo "Unexpanded school database configuration" >&2; exit 1
fi
escaped_password=$(printf '%s' "$POSTGRES_PASSWORD" | sed 's/\\/\\\\/g; s/"/\\"/g')
printf '"%s" "%s"\n' "$POSTGRES_USER" "$escaped_password" > /tmp/pgbouncer-school-users.txt
# edoburu runs as postgres; no root-only system path is written here.
exec pgbouncer /tmp/pgbouncer-school.ini
